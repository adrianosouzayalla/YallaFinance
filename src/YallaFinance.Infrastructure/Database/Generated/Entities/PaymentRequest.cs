using System;
using System.Collections.Generic;

namespace YallaFinance.Infrastructure.Database.Generated.Entities;

/// <summary>
/// Oferta de pagamento e ciclo de vida do link; não duplica valor, cliente, vencimento ou contrato.
/// </summary>
public partial class PaymentRequest
{
    /// <summary>
    /// Identificador interno UUID gerado pela aplicação; nunca é token público.
    /// </summary>
    public Guid Id { get; set; }

    /// <summary>
    /// Tenant proprietário; participa de todas as relações financeiras.
    /// </summary>
    public Guid TenantId { get; set; }

    /// <summary>
    /// Cobrança existente à qual pertence o registro; não cria outra cobrança.
    /// </summary>
    public Guid ChargeId { get; set; }

    /// <summary>
    /// Active, Expired, Canceled ou Completed; ciclo do link, não estado do dinheiro.
    /// </summary>
    public string Status { get; set; } = null!;

    /// <summary>
    /// Unique opaque code generated by the application and used to locate the payment request from its public link.
    /// </summary>
    public string TokenHash { get; set; } = null!;

    /// <summary>
    /// Expiração do link; validada pelo relógio do servidor, independentemente do status persistido.
    /// </summary>
    public DateTime ExpiresAt { get; set; }

    /// <summary>
    /// Nota operacional opcional; não expor no checkout.
    /// </summary>
    public string? Note { get; set; }

    /// <summary>
    /// Criacao UTC, imutavel no runtime. Data historica preservada quando conhecida; ausencias preenchidas na Feature 22/Fase 1.
    /// </summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>
    /// Ultima alteracao UTC; NULL na criacao. Datas legadas podem coincidir com a criacao pelo padrao anterior.
    /// </summary>
    public DateTime? UpdatedAt { get; set; }

    /// <summary>
    /// Quando o link Active foi encerrado pela liquidação da Charge.
    /// </summary>
    public DateTime? CompletedAt { get; set; }

    /// <summary>
    /// Quando a aplicação persistiu a expiração; pode ocorrer depois de expires_at.
    /// </summary>
    public DateTime? ExpiredAt { get; set; }

    /// <summary>
    /// Instante de cancelamento do link pelo operador.
    /// </summary>
    public DateTime? CanceledAt { get; set; }

    /// <summary>
    /// Identidade do operador que cancelou; obrigatória em Canceled.
    /// </summary>
    public string? CanceledBy { get; set; }

    /// <summary>
    /// RequestPayment ou ChargeSettledElsewhere; só em Completed.
    /// </summary>
    public string? CompletionReason { get; set; }

    /// <summary>
    /// FK core.user. Legado atribuido administrativamente ao ADMIN na Feature 22/Fase 1; nao comprova autoria original.
    /// </summary>
    public Guid CreatedBy { get; set; }

    /// <summary>
    /// FK core.user; NULL sem alteracao. Legado com data de alteracao atribuido administrativamente ao ADMIN.
    /// </summary>
    public Guid? UpdatedBy { get; set; }

    public virtual Charge Charge { get; set; } = null!;

    public virtual User CreatedByNavigation { get; set; } = null!;

    public virtual ICollection<PaymentAttempt> PaymentAttempts { get; set; } = new List<PaymentAttempt>();

    public virtual ICollection<PaymentCommandReceipt> PaymentCommandReceipts { get; set; } = new List<PaymentCommandReceipt>();

    public virtual ICollection<PaymentRequestMethod> PaymentRequestMethods { get; set; } = new List<PaymentRequestMethod>();

    public virtual Tenant Tenant { get; set; } = null!;

    public virtual User? UpdatedByNavigation { get; set; }
}
